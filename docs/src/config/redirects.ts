const prefixed = (prefix: string, map: Record<string, string>): Record<string, string> =>
  Object.fromEntries(Object.entries(map).map(([from, to]) => [`${prefix}/${from}`, to]));

const allTo = (prefix: string, paths: string[], to: string): Record<string, string> => Object.fromEntries(paths.map(path => [`${prefix}/${path}`, to]));

