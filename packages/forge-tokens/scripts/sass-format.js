const INTEGER_KEY_PATTERN = /^(0|[1-9]\d*)$/;
const IDENTIFIER_KEY_PATTERN = /^[a-z][a-z0-9-]*$/i;

/**
 * Formats a token key as a Sass map key.
 *
 * Integer keys are emitted as numbers, identifiers are left bare, and everything else (such as keys with leading zeros) is quoted.
 * Pass `quote` to always emit a quoted string key.
 *
 * @param {string} key The key to format.
 * @param {boolean} [quote] Whether to always quote the key.
 * @returns {string} The Sass map key.
 */
export function toSassKey(key, quote = false) {
  return !quote && (INTEGER_KEY_PATTERN.test(key) || IDENTIFIER_KEY_PATTERN.test(key)) ? key : `'${key}'`;
}

/**
 * Determines whether a CSS value contains a comma outside of any parentheses.
 *
 * @param {string} value The CSS value to check.
 * @returns {boolean} `true` if the value is a top-level comma separated list.
 */
export function hasTopLevelComma(value) {
  let depth = 0;
  for (const char of value) {
    if (char === '(') {
      depth++;
    } else if (char === ')') {
      depth--;
    } else if (char === ',' && depth === 0) {
      return true;
    }
  }
  return false;
}

/**
 * Formats a resolved token value as a Sass value.
 *
 * Comma separated values (such as shadows and font families) are wrapped in parentheses so that they remain a single Sass list value within a map.
 *
 * @param {import('style-dictionary/types').TransformedToken} token The token to format.
 * @returns {string} The Sass value.
 */
export function toSassValue(token) {
  const value = String(token.$value);
  return hasTopLevelComma(value) ? `(${value})` : value;
}

/**
 * Builds a tree from the tokens under `root`, where the first `depth` path segments below the root
 * are nested levels and any remaining segments are joined with a dash to form the leaf key.
 */
function buildTree(tokens, root, depth) {
  const tree = new Map();
  for (const token of tokens) {
    const segments = token.path.slice(root.length);
    const levels = segments.slice(0, depth);
    const leafKey = segments.slice(depth).join('-');
    let node = tree;
    for (const level of levels) {
      if (!node.has(level)) {
        node.set(level, new Map());
      }
      node = node.get(level);
    }
    node.set(leafKey, toSassValue(token));
  }
  return tree;
}

function renderMap(node, indent, quoteKeys) {
  const pad = '  '.repeat(indent + 1);
  const entries = [...node].map(
    ([key, value]) => `${pad}${toSassKey(key, quoteKeys)}: ${value instanceof Map ? renderMap(value, indent + 1, quoteKeys) : value}`
  );
  return `(\n${entries.join(',\n')}\n${'  '.repeat(indent)})`;
}

const startsWith = (path, root) => root.every((segment, i) => path[i] === segment);

/**
 * Style Dictionary format that emits one Sass variable per entry in `options.variables`.
 *
 * Each entry selects the tokens below `root` and is emitted as a `map` (default), a single `value`, or a Sass variable per token (`variables`).
 *
 * @type {import('style-dictionary/types').FormatFn}
 */
export function sassFormat({ dictionary, options }) {
  const blocks = options.variables.map(({ name, root, type = 'map', depth = 0, defaultable = false, quoteKeys = false }) => {
    const tokens = dictionary.allTokens.filter(token => startsWith(token.path, root));
    if (!tokens.length) {
      throw new Error(`No tokens found below "${root.join('.')}" for Sass variable "${name}".`);
    }
    if (type === 'variables') {
      return tokens.map(token => `$${token.path.slice(root.length).join('-')}: ${toSassValue(token)};`).join('\n');
    }
    const suffix = defaultable ? ' !default' : '';
    const value = type === 'value' ? toSassValue(tokens[0]) : renderMap(buildTree(tokens, root, depth), 0, quoteKeys);
    return `$${name}: ${value}${suffix};`;
  });

  return `// Do not edit directly, this file was generated by Style Dictionary from the JSON in \`tokens/\`.\n\n${blocks.join('\n\n')}\n`;
}
