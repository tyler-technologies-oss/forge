import * as fs from 'fs';
import * as path from 'path';

const GLOBAL_TYPES = new Set(['Date', 'File', 'FileList', 'Blob', 'Array', 'Record', 'Map', 'Set', 'Promise', 'Partial', 'Readonly']);
const EVENT_NAME_PATTERN = /^[a-z][a-z0-9-]*$/;

/**
 * This plugin generates React 19 JSX typings (`IntrinsicElements` augmentation) for every custom element in the manifest.
 *
 * Prop and element types are imported from the package's own generated `.d.ts` files, so the output must live next to them
 * (`dist/`). Event handler props are named `on<event-name>` exactly as dispatched, which is how React 19 attaches
 * listeners to custom elements (`addEventListener(key.slice(2), ...)`).
 */
export default function forgeJsxTypesPlugin({ outDir = 'dist', fileName = 'jsx.d.ts' } = {}) {
  return {
    name: 'FORGE - JSX-TYPES',
    packageLinkPhase({ customElementsManifest }) {
      const source = generate(customElementsManifest);
      fs.mkdirSync(outDir, { recursive: true });
      fs.writeFileSync(path.join(outDir, fileName), source);
    }
  };
}

function generate(manifest) {
  const forgeTypes = manifest.forgeTypes ?? {};
  const imports = new Map();
  const entries = [];

  const addImport = (name, modulePath) => {
    const specifier = `./${modulePath.replace(/^src\/lib\//, '').replace(/\.ts$/, '.js')}`;
    if (!imports.has(specifier)) {
      imports.set(specifier, new Set());
    }
    imports.get(specifier).add(name);
  };

  const elements = manifest.modules
    .flatMap(mod => (mod.declarations ?? []).map(declaration => ({ declaration, modulePath: mod.path })))
    .filter(({ declaration }) => declaration.kind === 'class' && declaration.customElement && declaration.tagName)
    .sort((a, b) => a.declaration.tagName.localeCompare(b.declaration.tagName));

  for (const { declaration, modulePath } of elements) {
    addImport(declaration.name, modulePath);
    entries.push(createEntry({ declaration, forgeTypes, addImport }));
  }

  const importLines = [...imports.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([specifier, names]) => `import type { ${[...names].sort().join(', ')} } from '${specifier}';`);

  return `// Generated by plugins/cem/jsx-types.mjs from custom-elements.json. Do not edit.
import type * as React from 'react';
${importLines.join('\n')}

/** Props shared by every Forge AI element in JSX: standard HTML attributes, \`ref\`, \`key\`, \`class\`, plus the element's own props, attributes, and events. */
type ForgeAiElementProps<E extends HTMLElement, Props extends keyof E, Attrs = {}, Events = {}> = Omit<
  React.HTMLAttributes<E>,
  Props | keyof Attrs | keyof Events
> &
  React.ClassAttributes<E> & { class?: string } & Partial<Pick<E, Props>> &
  Attrs &
  Events;

/** Custom element tag names mapped to their JSX props. */
export interface ForgeAiIntrinsicElements {
${entries.join('\n')}
}

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements extends ForgeAiIntrinsicElements {}
  }
}
`;
}

function createEntry({ declaration, forgeTypes, addImport }) {
  const { name: className, tagName } = declaration;

  const props = (declaration.members ?? []).filter(
    member => member.kind === 'field' && (member.privacy ?? 'public') === 'public' && !member.static && !member.readonly
  );
  const propNames = new Set(props.map(prop => prop.name));

  const attrs = (declaration.attributes ?? [])
    .filter(attr => attr.fieldName && attr.name !== attr.fieldName && propNames.has(attr.fieldName) && !defaultsToTrue(attr, props))
    .map(attr => `    /** Attribute form of \`${attr.fieldName}\`. */\n    ${quote(attr.name)}?: ${className}[${quote(attr.fieldName)}];`);

  const events = [];
  for (const event of declaration.events ?? []) {
    if (!EVENT_NAME_PATTERN.test(event.name ?? '') || event.type?.text === 'Event') {
      continue;
    }
    const type = resolveEventType({ text: event.type?.text, forgeTypes, addImport, tagName, eventName: event.name });
    events.push(`    ${docComment(event.description, 4)}${quote(`on${event.name}`)}?: (event: ${type}) => void;`);
  }

  const propUnion = props.length ? props.map(prop => quote(prop.name)).join(' | ') : 'never';
  const attrType = attrs.length ? `{\n${attrs.join('\n')}\n  }` : '{}';
  const eventType = events.length ? `{\n${events.join('\n')}\n  }` : '{}';

  return `  ${docComment(describe(declaration), 2)}${quote(tagName)}: ForgeAiElementProps<${className}, ${propUnion}, ${attrType}, ${eventType}>;`;
}

/**
 * A boolean that defaults to true cannot be turned off through an attribute (a present attribute is always true), so the
 * kebab-case form is omitted and only the camelCase property form is typed.
 */
function defaultsToTrue(attr, props) {
  const prop = props.find(p => p.name === attr.fieldName);
  return (attr.default ?? prop?.default) === 'true';
}

function resolveEventType({ text, forgeTypes, addImport, tagName, eventName }) {
  const detail = /^CustomEvent<([\s\S]+)>$/.exec(text ?? '')?.[1].trim();
  if (!detail) {
    return 'CustomEvent';
  }

  const identifiers = [...new Set(detail.replace(/'[^']*'/g, '').match(/\b[A-Z][A-Za-z0-9_]*\b/g) ?? [])];
  const unresolved = identifiers.filter(id => !GLOBAL_TYPES.has(id) && !forgeTypes[id]);
  if (unresolved.length) {
    throw new Error(
      `[jsx-types] ${tagName} "${eventName}": cannot resolve event detail type(s) ${unresolved.join(', ')}. Export the type from the component module and fix the @event JSDoc.`
    );
  }

  identifiers.filter(id => forgeTypes[id]).forEach(id => addImport(id, forgeTypes[id].path));
  return `CustomEvent<${detail}>`;
}

function describe(declaration) {
  const parts = [declaration.summary ?? declaration.description].filter(Boolean);
  const slots = (declaration.slots ?? []).map(slot => `- \`${slot.name || '(default)'}\`: ${slot.description ?? ''}`.trim());
  if (slots.length) {
    parts.push(`Slots:\n${slots.join('\n')}`);
  }
  return parts.join('\n\n');
}

function quote(value) {
  return `'${value}'`;
}

function docComment(text, indent) {
  if (!text?.trim()) {
    return '';
  }
  const pad = ' '.repeat(indent);
  const lines = text
    .replace(/\*\//g, '*\\/')
    .split('\n')
    .map(line => `${pad} * ${line}`.trimEnd());
  return `/**\n${lines.join('\n')}\n${pad} */\n${pad}`;
}
